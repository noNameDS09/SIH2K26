export function translate(key: string, languageCode = "en-IN", fallback?: string): string {
  const norm = (languageCode || "en-IN").trim();
  const dict = TRANSLATIONS[norm];
  if (dict && dict[key]) return dict[key];

  // Try language prefix (e.g. "hi" from "hi-IN")
  const prefix = norm.split("-")[0];
  const matchedKey = Object.keys(TRANSLATIONS).find((k) => k.startsWith(prefix));
  if (matchedKey && TRANSLATIONS[matchedKey]?.[key]) {
    return TRANSLATIONS[matchedKey][key];
  }

  // Fallback to Hindi if not English
  if (!norm.startsWith("en") && TRANSLATIONS["hi-IN"]?.[key]) {
    return TRANSLATIONS["hi-IN"][key];
  }

  // Fallback to English
  if (TRANSLATIONS["en-IN"]?.[key]) {
    return TRANSLATIONS["en-IN"][key];
  }

  return fallback || key;
}
